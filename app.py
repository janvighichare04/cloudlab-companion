import os
from pathlib import Path

import streamlit as st
from dotenv import load_dotenv
from openai import OpenAI

# --------------------------------------------------
# PAGE CONFIGURATION
# --------------------------------------------------
st.set_page_config(
    page_title="CloudLab Companion",
    page_icon="☁️",
    layout="wide",
    initial_sidebar_state="expanded",
)

# --------------------------------------------------
# LOAD EXTERNAL CSS
# --------------------------------------------------
CSS_PATH = Path(__file__).parent / "style.css"
if CSS_PATH.exists():
    st.markdown(
        f"<style>{CSS_PATH.read_text(encoding='utf-8')}</style>",
        unsafe_allow_html=True,
    )
else:
    st.warning("style.css was not found. Place it in the same folder as app.py.")

# --------------------------------------------------
# GEMINI API CONFIGURATION
# --------------------------------------------------
load_dotenv(Path(__file__).parent / ".env")

api_key = os.getenv("GEMINI_API_KEY")
client = None

if api_key:
    client = OpenAI(
        api_key=api_key,
        base_url="https://generativelanguage.googleapis.com/v1beta/openai/",
    )

# --------------------------------------------------
# SESSION STATE
# --------------------------------------------------
if "messages" not in st.session_state:
    st.session_state.messages = []

if "pending_question" not in st.session_state:
    st.session_state.pending_question = ""

# Count submitted questions in this browser session.
questions_asked = sum(
    1 for message in st.session_state.messages
    if message.get("role") == "user"
)

# --------------------------------------------------
# SIDEBAR
# --------------------------------------------------
with st.sidebar:
    st.markdown(
        """
        <div class="sidebar-brand">
            <div class="sidebar-brand-icon">☁️</div>
            <div>
                <div class="sidebar-brand-title">CloudLab</div>
                <div class="sidebar-brand-subtitle">Your cloud learning space</div>
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )
    st.divider()
    st.subheader("Quick questions")

    quick_questions = {
        "☁️ AWS basics": "Explain AWS cloud computing in simple words.",
        "🐧 Linux commands": "Explain five useful Linux commands with examples.",
        "🔄 CI/CD pipeline": "Explain a CI/CD pipeline with a simple example.",
        "🛠️ Troubleshooting": (
            "How should I troubleshoot an EC2 server that is not responding?"
        ),
    }

    for label, prompt in quick_questions.items():
        if st.button(label, key=f"quick_{label}", use_container_width=True):
            st.session_state.pending_question = prompt
            st.rerun()

    st.divider()
    st.subheader("This session")
    st.metric("Questions asked", questions_asked)

    if st.button("🗑️ Clear chat history", use_container_width=True):
        st.session_state.messages = []
        st.session_state.pending_question = ""
        st.rerun()

    st.caption("Responses generated by Gemini AI")

# --------------------------------------------------
# HERO HEADER
# --------------------------------------------------
st.markdown(
    """
    <section class="hero">
        <div class="hero-eyebrow">LEARN <span>·</span> EXPLORE <span>·</span> BUILD</div>
        <h1>CloudLab Companion <span class="hero-cloud">☁️</span></h1>
        <p>
            Your AI-powered study partner for cloud computing, AWS, Linux,
            DevOps, and hands-on technical troubleshooting.
        </p>
        <div class="hero-tags">
            <span>Cloud fundamentals</span>
            <span>AWS services</span>
            <span>Linux</span>
            <span>DevOps &amp; CI/CD</span>
        </div>
    </section>
    """,
    unsafe_allow_html=True,
)

# --------------------------------------------------
# OVERVIEW METRICS
# --------------------------------------------------
metric1, metric2, metric3 = st.columns(3)
with metric1:
    st.metric("Learning areas", "04")
with metric2:
    st.metric("AI provider", "Gemini")
with metric3:
    st.metric("Questions asked", questions_asked)

# --------------------------------------------------
# LEARNING TOPICS
# --------------------------------------------------
st.markdown(
    """
    <div class="section-heading">
        <div class="section-kicker">YOUR LEARNING DASHBOARD</div>
        <h2>Explore learning areas</h2>
        <p>Choose a topic to start exploring with practical, student-friendly explanations.</p>
    </div>
    """,
    unsafe_allow_html=True,
)

topics = [
    {
        "icon": "☁️",
        "title": "Cloud Computing",
        "description": "Understand cloud concepts, service models, deployment, and infrastructure.",
        "prompt": "Explain cloud computing and its service models with practical examples.",
        "class": "cloud",
    },
    {
        "icon": "🔷",
        "title": "AWS Services",
        "description": "Explore EC2, S3, IAM, networking, storage, and core AWS services.",
        "prompt": "Explain AWS EC2, S3, and IAM with practical examples for a beginner.",
        "class": "aws",
    },
    {
        "icon": "🐧",
        "title": "Linux Essentials",
        "description": "Practise terminal commands, file permissions, processes, and troubleshooting.",
        "prompt": "Teach me five important Linux commands with examples and explain when to use each.",
        "class": "linux",
    },
    {
        "icon": "🔄",
        "title": "DevOps & CI/CD",
        "description": "Learn Git, automation, deployment pipelines, and delivery workflows.",
        "prompt": "Explain DevOps and a CI/CD pipeline using a simple website project as an example.",
        "class": "devops",
    },
]

topic_columns = st.columns(4, gap="medium")
for index, topic in enumerate(topics):
    with topic_columns[index]:
        st.markdown(
            f"""
            <div class="topic-card {topic['class']}">
                <div class="topic-icon">{topic['icon']}</div>
                <div class="topic-title">{topic['title']}</div>
                <div class="topic-description">{topic['description']}</div>
            </div>
            """,
            unsafe_allow_html=True,
        )
        if st.button(
            "Explore topic ↗",
            key=f"topic_{index}",
            use_container_width=True,
        ):
            st.session_state.pending_question = topic["prompt"]
            st.rerun()

# --------------------------------------------------
# CHAT
# --------------------------------------------------
st.markdown(
    """
    <div class="section-heading chat-section-heading">
        <div class="section-kicker">ASK · LEARN · APPLY</div>
        <h2>Chat with CloudLab</h2>
        <p>Ask a question, describe an error, or request a step-by-step explanation.</p>
    </div>
    """,
    unsafe_allow_html=True,
)

if not st.session_state.messages:
    st.markdown(
        """
        <div class="empty-state">
            <div class="empty-state-icon">💬</div>
            <div class="empty-state-title">What are you working on today?</div>
            <div class="empty-state-text">
                Try asking about an AWS service, a Linux command, or a deployment issue.
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )

for message in st.session_state.messages:
    role = "user" if message["role"] == "user" else "assistant"
    with st.chat_message(role):
        st.markdown(message["content"])

# Use a form so the visible input and empty-input validation are both available.
with st.form("question_form", clear_on_submit=True):
    question = st.text_input(
        "Your question",
        placeholder="e.g. My website is not opening on EC2. How do I troubleshoot it?",
        max_chars=2001,
    )
    submitted = st.form_submit_button("Ask CloudLab →", use_container_width=True)

if not submitted:
    question = None

# A topic or quick question selected above takes priority on this rerun.
if st.session_state.pending_question:
    question = st.session_state.pending_question
    st.session_state.pending_question = ""

if question is not None:
    question = question.strip()

    if not question:
        st.warning("Please enter a question before submitting.")
    elif len(question) > 2000:
        st.warning("Your question is too long. Please keep it within 2,000 characters.")
    elif client is None:
        st.error(
            "Gemini API key is missing. Add GEMINI_API_KEY to your local .env file "
            "or configure it in your deployment secrets."
        )
    else:
        st.session_state.messages.append({"role": "user", "content": question})
        try:
            with st.spinner("CloudLab is preparing your answer..."):
                response = client.chat.completions.create(
                    model="gemini-3.6-flash",
                    messages=[
                        {
                            "role": "system",
                            "content": (
                                "You are CloudLab Companion, a helpful learning assistant "
                                "specializing in cloud computing, AWS, Linux, DevOps, CI/CD, "
                                "and technical troubleshooting. Explain concepts clearly "
                                "with practical examples and step-by-step instructions. "
                                "For commands, explain what they do and mention important "
                                "safety considerations. If a question is unrelated, respond "
                                "politely and helpfully."
                            ),
                        },
                        *st.session_state.messages,
                    ],
                    temperature=0.5,
                )

            answer = response.choices[0].message.content
            if not answer or not answer.strip():
                answer = "I couldn't generate a response. Please try asking another way."

            st.session_state.messages.append(
                {"role": "assistant", "content": answer}
            )
            st.rerun()

        except Exception:
            # Do not count failed requests as completed questions.
            st.session_state.messages.pop()
            st.error(
                "Sorry, I couldn't get a response from Gemini. Check your internet "
                "connection and API configuration, then try again."
            )

